// Full local protocol-to-domain journey. OAuth, SDK, public HTTP handlers, bridge client,
// entry handler and domain executors are real; Convex HTTP/persistence are synthetic.
import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { createHash, randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { generateKeyPair, exportJWK } from 'jose';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { createMcpHandler } from '../api/_lib/mcp/handler.js';
import { createOAuth } from '../api/_lib/mcp/oauth.js';
import { mcpStore } from '../api/_lib/mcp/store.js';
import { runTool } from '../api/_lib/mcp/application.js';
import { sealToken, credentialContext } from '../api/_lib/layla/customer-meta.js';
import { blueHarness, seedTenant } from './helpers/blue-tenant.mjs';
import { GREEN_CLOUD, GREEN_SITE, GREEN_SECRET } from './helpers/green-env.mjs';

const bundle = await build({ entryPoints: [fileURLToPath(new URL('../convex/mcp.ts', import.meta.url))], bundle: true, write: false, platform: 'node', format: 'esm' });
const { execute } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
process.env.MCP_ENABLED = 'true';
process.env.CONVEX_SERVICE_SECRET = GREEN_SECRET;
process.env.PUBLIC_SITE_ORIGIN = 'https://www.bznsflowai.com';

test('OAuth connection → SDK discovery → domain writes/approval/replay → refresh → revoke', { timeout: 60000 }, async t => {
  const h = blueHarness({ start: Date.now() });
  await h.enable();
  await h.m.db.insert('blueMessagingSettings', { key: 'hasib', enabled: true });
  const owner = await seedTenant(h.m, { plan: 'ascend', sector: 'Real estate' });
  assert.equal((await h.messaging('activate', { sessionHash: owner.sessionHash })).ok, true);
  const sessionToken = '1'.repeat(64), csrf = '2'.repeat(64);
  await h.m.db.insert('sessions', { accountId: owner.accountId, tokenHash: createHash('sha256').update(sessionToken).digest('hex'), createdAt: h.m.now(), expiresAt: h.m.now() + 86400000 });
  const { privateKey } = await generateKeyPair('RS256', { extractable: true });
  const jwk = { ...await exportJWK(privateKey), kid: 'synthetic-flow', use: 'sig', alg: 'RS256' };
  const server = createServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }));
  const origin = `http://127.0.0.1:${server.address().port}`, resource = `${origin}/api/mcp`;
  const env = { NODE_ENV: 'test', PUBLIC_SITE_ORIGIN: origin, MCP_ENABLED: 'true', MCP_COOKIE_KEYS: 'k'.repeat(48), MCP_OAUTH_ENCRYPTION_KEY: 'a'.repeat(64), MCP_OAUTH_JWKS: JSON.stringify({ keys: [jwk] }), CONVEX_CLOUD_URL: GREEN_CLOUD, CONVEX_SITE_URL: GREEN_SITE, CONVEX_SERVICE_SECRET: GREEN_SECRET, LAYLA_CREDENTIAL_ENCRYPTION_KEY: 'b'.repeat(64), LAYLA_META_APP_SECRET: 'synthetic-secret' };
  const providerToken = 'synthetic-meta-token-for-local-tests';
  await h.m.db.patch(owner.rowId, { integration: { ...owner.integration, credential: sealToken(providerToken, credentialContext(owner.sessionHash, owner.integration), env) } });
  let providerHealthy = true, providerReads = 0, providerNameStatus = 'APPROVED';
  const providerFetch = async (input, init) => {
    const url = new URL(input);
    assert.equal(url.origin, 'https://graph.facebook.com');
    assert.equal(init.method, 'GET', 'connection checks must never register, subscribe or send');
    assert.equal(init.headers.Authorization, `Bearer ${providerToken}`);
    providerReads++;
    if (!providerHealthy) return Response.json({ error: { code: 190 } }, { status: 401 });
    const callback = 'https://www.bznsflowai.com/api/layla-meta-webhook';
    if (url.pathname === `/v25.0/${owner.integration.waba}/subscribed_apps`) return Response.json({ data: [{ whatsapp_business_api_data: { id: owner.integration.app }, override_callback_uri: callback }] });
    assert.equal(url.pathname, `/v25.0/${owner.integration.phone}`);
    if (url.searchParams.get('fields') === 'name_status') return Response.json({ name_status: providerNameStatus });
    assert.equal(url.searchParams.get('fields'), 'id,status,is_on_biz_app,webhook_configuration');
    return Response.json({ id: owner.integration.phone, status: 'CONNECTED', is_on_biz_app: false, webhook_configuration: { whatsapp_business_account: callback } });
  };
  let bridgeCalls = 0;
  const store = mcpStore({ env, fetcher: async (url, init) => {
    assert.equal(url, `${GREEN_SITE}/mcp-internal`, 'the synthetic bridge must never contact a deployment');
    assert.equal(init.headers.Authorization, `Bearer ${GREEN_SECRET}`);
    bridgeCalls++;
    try { return Response.json({ ok: true, value: await execute._handler(h.m.ctx, JSON.parse(init.body)) }); }
    catch (error) { return Response.json({ ok: false, reason: /^[a-z_]{3,60}$/.test(error.message) ? error.message : 'mcp_unavailable' }); }
  } });
  const handlers = [0, 1].map(() => createMcpHandler({ env, store, provider: createOAuth({ env, store }), execute: args => runTool({ ...args, fetcher: providerFetch }) }));
  let instance = 0;
  server.on('request', (req, res) => handlers[instance++ % 2](req, res));
  const jar = new Map([['bf_session', sessionToken], ['bf_csrf', csrf]]);
  const request = async (path, options = {}) => {
    const response = await fetch(new URL(path, origin), { redirect: 'manual', ...options, headers: { Cookie: [...jar].map(([k, v]) => `${k}=${v}`).join('; '), ...options.headers } });
    for (const cookie of response.headers.getSetCookie()) {
      const pair = cookie.split(';')[0], at = pair.indexOf('=');
      jar.set(pair.slice(0, at), pair.slice(at + 1));
    }
    return response;
  };
  const manage = async body => {
    const response = await request('/api/mcp/manage', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json', 'x-csrf-token': csrf }, body: JSON.stringify(body) });
    assert.equal(response.status, 200, await response.clone().text());
    return response.json();
  };
  const registration = await request('/oauth/reg', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ client_name: 'Local flow acceptance', redirect_uris: ['http://127.0.0.1:3456/callback'], grant_types: ['authorization_code', 'refresh_token'], response_types: ['code'], token_endpoint_auth_method: 'none' }) });
  assert.equal(registration.status, 201, await registration.clone().text());
  const client = await registration.json(), verifier = 'v'.repeat(64);
  const authorize = await request('/oauth/auth?' + new URLSearchParams({ client_id: client.client_id, redirect_uri: client.redirect_uris[0], response_type: 'code', scope: 'workspace:read workspace:write', resource, code_challenge: createHash('sha256').update(verifier).digest('base64url'), code_challenge_method: 'S256', state: 'local-flow', prompt: 'consent' }));
  assert.equal(authorize.status, 303);
  const viewResponse = await request('/api/mcp/manage?interaction=true');
  assert.equal(viewResponse.status, 200);
  const view = await viewResponse.json();
  const consent = await manage({ action: 'consent', allow: true, interactionUid: view.interaction.uid });
  const resumed = await request(consent.redirect);
  assert.equal(resumed.status, 303);
  const callback = new URL(resumed.headers.get('location'));
  assert.equal(callback.origin, 'http://127.0.0.1:3456');
  assert.equal(callback.searchParams.get('state'), 'local-flow');
  const tokenRequest = body => request('/oauth/token', { method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ client_id: client.client_id, resource, ...body }) });
  const tokenResponse = await tokenRequest({ grant_type: 'authorization_code', code: callback.searchParams.get('code'), code_verifier: verifier, redirect_uri: client.redirect_uris[0] });
  assert.equal(tokenResponse.status, 200, await tokenResponse.clone().text());
  const tokens = await tokenResponse.json();
  const [connection] = h.m.table('mcpConnections');
  assert.equal(connection.accountId, owner.accountId);
  assert.ok(connection.grantId);
  let bearer = tokens.access_token;
  const sdk = new Client({ name: 'full-flow-test', version: '1.0.0' });
  t.after(() => sdk.close());
  const transport = new StreamableHTTPClientTransport(new URL(resource), { fetch: (url, init) => fetch(url, { ...init, headers: { ...Object.fromEntries(new Headers(init?.headers)), Authorization: `Bearer ${bearer}` } }) });
  await sdk.connect(transport);
  const names = [];
  let cursor;
  do {
    const page = await sdk.listTools(cursor ? { cursor } : {});
    assert.ok(page.tools.length <= 60);
    names.push(...page.tools.map(tool => tool.name));
    cursor = page.nextCursor;
  } while (cursor);
  assert.equal(new Set(names).size, names.length);
  assert.ok(names.includes('bznsflow_business_state'));
  assert.ok(names.includes('bznsflow_hasib_overview'));
  assert.ok(!names.includes('bznsflow_hasib_dental_visits'));
  const call = (name, args = {}) => sdk.callTool({ name, arguments: args });
  const read = await call('bznsflow_business_state');
  assert.equal(read.structuredContent.result.profile.businessName, 'Blue Studio');
  assert.ok(!JSON.stringify(read).includes(owner.sessionHash), 'setup authority never reaches the client');
  const sector = await call('bznsflow_hasib_overview');
  assert.equal(sector.structuredContent.status, 'completed');
  const writeArgs = { requestId: randomUUID(), timezone: 'Asia/Muscat' };
  const write = await call('bznsflow_dashboard_set_timezone', writeArgs);
  assert.equal(write.structuredContent.status, 'completed');
  assert.equal(h.m.table('blueBusinessSettings').find(row => row.accountId === owner.accountId).timezone, 'Asia/Muscat');
  assert.equal((await call('bznsflow_dashboard_set_timezone', writeArgs)).structuredContent.replay, true);
  const conflict = await call('bznsflow_dashboard_set_timezone', { ...writeArgs, timezone: 'UTC' });
  assert.equal(conflict.isError, true);
  assert.equal(conflict.content[0].text, 'idempotency_conflict');
  const pauseArgs = { requestId: randomUUID(), confirm: true };
  const proposed = (await call('bznsflow_messaging_pause', pauseArgs)).structuredContent;
  assert.equal(proposed.status, 'approval_required');
  assert.equal(h.m.table('blueMessagingControls')[0].active, true, 'consent is not approval to execute');
  await manage({ action: 'approve', connectionId: connection._id, runId: proposed.runId });
  const paused = await call('bznsflow_messaging_pause', pauseArgs);
  assert.equal(paused.structuredContent.status, 'completed');
  assert.equal(h.m.table('blueMessagingControls')[0].active, false);
  assert.equal(h.m.table('blueMessagingControls')[0].reason, 'owner_paused');
  assert.equal((await call('bznsflow_messaging_pause', pauseArgs)).structuredContent.replay, true);
  // Make the seeded last inspection old enough for the real 5-second refresh throttle.
  await h.m.db.patch(owner.rowId, { checkedAt: Date.now() - 6000 });
  const checked = await call('bznsflow_messaging_check_connection');
  assert.ok(!checked.isError, JSON.stringify(checked));
  assert.equal(checked.structuredContent.status, 'completed');
  assert.equal(providerReads, 3);
  assert.equal((await h.m.db.get(owner.rowId)).operation, undefined);
  assert.equal(h.m.table('blueMessagingControls')[0].active, false, 'checking a connection never overrides the owner pause');
  const throttled = await call('bznsflow_messaging_check_connection');
  assert.equal(throttled.isError, true);
  assert.equal(throttled.content[0].text, 'refresh_throttled');
  assert.equal(providerReads, 3, 'an immediate repeat performs no extra provider requests');
  await h.m.db.patch(owner.rowId, { checkedAt: Date.now() - 6000 });
  providerHealthy = false;
  assert.equal((await call('bznsflow_messaging_check_connection')).isError, true);
  const unavailable = await h.m.db.get(owner.rowId);
  assert.equal(unavailable.status, 'reconciliation_required');
  assert.equal(unavailable.operation, undefined, 'provider failure releases the durable refresh claim');
  const readsBeforeRecovery = providerReads;
  providerHealthy = true;
  providerNameStatus = 'AVAILABLE_WITHOUT_REVIEW';
  assert.equal((await call('bznsflow_messaging_check_connection')).structuredContent.status, 'completed');
  assert.equal(providerReads, readsBeforeRecovery + 3, 'recovery obtains fresh provider evidence');
  const recovered = await h.m.db.get(owner.rowId);
  assert.equal(recovered.status, 'connected');
  assert.equal(recovered.operation, undefined);
  assert.deepEqual(recovered.connectionChecks, { routing: true, registered: true, path: true, nameStatus: 'AVAILABLE_WITHOUT_REVIEW' });
  assert.equal(h.m.table('blueMessagingControls')[0].active, false);
  const status = await call('bznsflow_requests_status', { runId: proposed.runId });
  assert.equal(status.structuredContent.result.status, 'completed');
  const invalid = await call('bznsflow_dashboard_set_timezone', { requestId: randomUUID(), timezone: 'UTC', accountId: 'foreign' });
  assert.equal(invalid.isError, true);
  assert.equal(invalid.content[0].text, 'invalid_arguments');
  assert.equal((await call('bznsflow_execute_arbitrary_sql')).isError, true);
  const refreshed = await tokenRequest({ grant_type: 'refresh_token', refresh_token: tokens.refresh_token, scope: 'openid workspace:read workspace:write' });
  assert.equal(refreshed.status, 200, await refreshed.clone().text());
  const rotated = await refreshed.json();
  assert.notEqual(rotated.refresh_token, tokens.refresh_token);
  bearer = rotated.access_token;
  assert.equal((await call('bznsflow_business_state')).structuredContent.status, 'completed', 'the refreshed token resolves to the same persisted connection');
  await manage({ action: 'revoke', connectionId: connection._id });
  const denied = await request('/api/mcp', { method: 'POST', headers: { Authorization: `Bearer ${bearer}`, 'Content-Type': 'application/json', Accept: 'application/json, text/event-stream' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/list', params: {} }) });
  assert.equal(denied.status, 401);
  assert.match(denied.headers.get('www-authenticate'), /oauth-protected-resource\/api\/mcp/);
  assert.ok(h.m.table('mcpConnections')[0].revokedAt);
  const revokedRefresh = await tokenRequest({ grant_type: 'refresh_token', refresh_token: rotated.refresh_token });
  assert.equal(revokedRefresh.status, 400);
  assert.equal((await revokedRefresh.json()).error, 'invalid_grant', 'a revoked connection cannot be revived by refresh');
  await sdk.close();
  // Allow the response-close/finally cleanup to settle before checking durable leases.
  for (let i = 0; i < 20 && h.m.table('mcpLeases').length; i++) await new Promise(resolve => setTimeout(resolve, 10));
  assert.equal(h.m.table('mcpLeases').length, 0);
  assert.equal(h.m.table('blueMessages').length, 0, 'the acceptance journey sends no messages');
  assert.ok(bridgeCalls > 30);
});
